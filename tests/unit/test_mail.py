# -- Stale token gap --

def test_mail_stale_token_gap(node, remote_node_id):
    """Stale since token returns gap flag."""
    r1 = _send(node, remote_node_id, body={"type": "text", "content": "msg1"})

    # Get the rowid of msg1
    poll1 = _poll(node)
    token = poll1["next_token"]

    # Delete msg1 (simulating TTL purge)
    _ack(node, [r1["message_id"]], "deleted")

    # Send a new message
    _send(node, remote_node_id, body={"type": "text", "content": "msg2"})

    # Poll with stale token — should indicate gap
    poll2 = _poll(node, since=token)
    assert poll2["gap"] is True
    assert len(poll2["messages"]) == 1


