# -- Mailbox policy --

def test_mail_accept_whitelist(remote_node_id):
    """Whitelist mode rejects non-whitelisted senders."""
    n = FakeNode(config={"mail": {"accept_from": "whitelist", "whitelist": ["allowed_node"]}})
    set_node(n)

    result = _send(n, remote_node_id)
    assert result["status"] == "rejected"
    assert result["reason"] == "not_whitelisted"

    # Allowed node can send
    result2 = _send(n, "allowed_node")
    assert result2["status"] == "delivered"


def test_mail_accept_none():
    """Disabled mailbox rejects all messages."""
    n = FakeNode(config={"mail": {"accept_from": "none"}})
    set_node(n)

    result = _send(n, "anyone")
    assert result["status"] == "rejected"
    assert result["reason"] == "mailbox_disabled"


def test_mail_max_messages(node, remote_node_id):
    """Rejects when mailbox is full."""
    # Set low limit
    node._config["mail"]["max_messages"] = 3
    set_node(node)

    for i in range(3):
        r = _send(node, remote_node_id, body={"type": "text", "content": f"msg{i}"})
        assert r["status"] == "delivered"

    r = _send(node, remote_node_id, body={"type": "text", "content": "overflow"})
    assert r["status"] == "rejected"
    assert r["reason"] == "mailbox_full"


