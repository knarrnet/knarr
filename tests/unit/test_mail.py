# -- Storage methods --

def test_storage_mail_count():
    """count_mail and count_mail_unread work correctly."""
    s = Storage(":memory:")
    assert s.count_mail() == 0

    s.store_mail("id1", "from", "to", time.time(), "{}", None, "text", None, time.time() + 3600)
    s.store_mail("id2", "from", "to", time.time(), "{}", None, "text", None, time.time() + 3600)
    assert s.count_mail() == 2
    assert s.count_mail_unread("to") == 2

    s.ack_mail(["id1"], "to", "read")
    assert s.count_mail_unread("to") == 1
    s.close()


def test_storage_purge_expired_mail():
    """purge_expired_mail deletes only expired messages."""
    s = Storage(":memory:")
    now = time.time()
    s.store_mail("exp1", "from", "to", now, "{}", None, "text", None, now - 1)  # expired
    s.store_mail("alive1", "from", "to", now, "{}", None, "text", None, now + 3600)  # alive

    purged = s.purge_expired_mail(now)
    assert purged == 1
    assert s.count_mail() == 1
    s.close()


def test_storage_cross_thread_access():
    """SENTINEL: Storage must be accessible from non-main threads (SA-9a-001)."""
    import threading
    s = Storage(":memory:")
    now = time.time()
    errors = []

    def write_from_thread():
        try:
            s.store_mail("t1", "from", "to", now, "{}", None, "text", None, now + 3600)
        except Exception as e:
            errors.append(e)

    t = threading.Thread(target=write_from_thread)
    t.start()
    t.join()
    assert not errors, f"Cross-thread storage access failed: {errors[0]}"
    assert s.count_mail() == 1
    s.close()
