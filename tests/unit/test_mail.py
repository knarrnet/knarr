def test_mail_ttl_expiry(node, remote_node_id):
    """SENTINEL: Expired messages are purged by cleanup."""
    # Send with 0.001 hour TTL (3.6 seconds)
    _send(node, remote_node_id, ttl_hours=0.001)

    # Immediately visible
    poll1 = _poll(node)
    assert len(poll1["messages"]) == 1

    # Simulate time passing — purge
    node.storage.purge_expired_mail(time.time() + 10)

    # Now gone
    poll2 = _poll(node)
    assert len(poll2["messages"]) == 0


